#!/usr/bin/env python3
"""Exhaustively verify the tiny instances behind NRD.7--NRD.9.

Vectors in F_2^(Lq) are encoded as integers.  Every state and environment is
represented by its set of nonzero syndrome-column types.  Breadth-first
search in the corresponding Cayley graph computes the exact coset-leader
profile and hence the covering radius.
"""

from __future__ import annotations

import argparse
import json
from collections import deque
from itertools import combinations
from pathlib import Path


INF = 10**9


def syndrome_profile(width: int, support: set[int]) -> tuple[int, ...]:
    """Return exact word lengths in the Cayley graph generated by support."""
    distance = [INF] * (1 << width)
    distance[0] = 0
    queue = deque([0])
    while queue:
        syndrome = queue.popleft()
        next_distance = distance[syndrome] + 1
        for column in support:
            target = syndrome ^ column
            if distance[target] > next_distance:
                distance[target] = next_distance
                queue.append(target)
    return tuple(distance)


def block_types(block: int, dimension: int) -> tuple[set[int], set[int]]:
    """Return the embedded basis B_j and dense support D_j."""
    shift = block * dimension
    basis = {1 << (shift + coordinate) for coordinate in range(dimension)}
    dense = {value << shift for value in range(1, 1 << dimension)}
    return basis, dense


def selected_support(
    mask: int,
    bases: list[set[int]],
    dense_sets: list[set[int]],
) -> set[int]:
    """Use D_j when bit j is one and B_j when it is zero."""
    support: set[int] = set()
    for block, (basis, dense) in enumerate(zip(bases, dense_sets)):
        support.update(dense if (mask >> block) & 1 else basis)
    return support


def padded_columns(
    mask: int,
    bases: list[set[int]],
    dense_sets: list[set[int]],
) -> tuple[int, ...]:
    """Give every state/environment exactly q(2^L-1) columns."""
    columns: list[int] = []
    for block, (basis_set, dense_set) in enumerate(zip(bases, dense_sets)):
        basis = sorted(basis_set)
        dense = sorted(dense_set)
        if (mask >> block) & 1:
            columns.extend(dense)
        else:
            columns.extend(basis)
            columns.extend([basis[0]] * (len(dense) - len(basis)))
    return tuple(columns)


def directed_counts(left: int, right: int, blocks: int) -> tuple[int, int]:
    n01 = 0
    n10 = 0
    for block in range(blocks):
        a = (left >> block) & 1
        b = (right >> block) & 1
        n01 += int(a == 0 and b == 1)
        n10 += int(a == 1 and b == 0)
    return n01, n10


def verify_case(dimension: int, blocks: int) -> dict[str, int]:
    width = dimension * blocks
    bases: list[set[int]] = []
    dense_sets: list[set[int]] = []
    for block in range(blocks):
        basis, dense = block_types(block, dimension)
        bases.append(basis)
        dense_sets.append(dense)

    number = 1 << blocks
    common_length = blocks * ((1 << dimension) - 1)
    states = [selected_support(mask, bases, dense_sets) for mask in range(number)]

    # NRD uses B_j on P and D_j outside P.  selected_support uses the
    # opposite bit convention, so the environment mask is the complement of
    # P within the q active bits.
    active_mask = number - 1
    environments = [
        selected_support(active_mask ^ p_mask, bases, dense_sets)
        for p_mask in range(number)
    ]

    for mask, support in enumerate(states):
        columns = padded_columns(mask, bases, dense_sets)
        assert len(columns) == common_length
        assert set(columns) == support
        assert max(syndrome_profile(width, support)) < INF

    for p_mask, support in enumerate(environments):
        columns = padded_columns(active_mask ^ p_mask, bases, dense_sets)
        assert len(columns) == common_length
        assert set(columns) == support
        assert max(syndrome_profile(width, support)) < INF

    responses: list[list[int]] = [[0] * number for _ in range(number)]
    maximum_radius = 0
    for state_mask, state in enumerate(states):
        for p_mask, environment in enumerate(environments):
            radius = max(syndrome_profile(width, state | environment))
            expected = blocks + (dimension - 1) * sum(
                1
                for block in range(blocks)
                if ((p_mask >> block) & 1)
                and not ((state_mask >> block) & 1)
            )
            assert radius == expected, (
                dimension,
                blocks,
                state_mask,
                p_mask,
                radius,
                expected,
            )
            responses[state_mask][p_mask] = radius
            maximum_radius = max(maximum_radius, radius)

    minimum_doubled_nrd9_slack = INF
    for left, right in combinations(range(number), 2):
        observed = max(
            abs(responses[left][p_mask] - responses[right][p_mask])
            for p_mask in range(number)
        )
        n01, n10 = directed_counts(left, right, blocks)
        expected = (dimension - 1) * max(n01, n10)
        hamming = n01 + n10
        assert observed == expected
        doubled_slack = 2 * observed - (dimension - 1) * hamming
        assert doubled_slack >= 0
        minimum_doubled_nrd9_slack = min(
            minimum_doubled_nrd9_slack, doubled_slack
        )

    return {
        "L": dimension,
        "q": blocks,
        "w": width,
        "common_fragment_length": common_length,
        "states": number,
        "environments": number,
        "state_environment_pairs_checked": number * number,
        "unordered_state_pairs_checked": number * (number - 1) // 2,
        "maximum_observed_radius": maximum_radius,
        "minimum_doubled_NRD9_slack": minimum_doubled_nrd9_slack,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(
            "extremal_information/experiments/"
            "phase2_normalized_code_rate_distortion_results.json"
        ),
    )
    args = parser.parse_args()

    cases = [(2, 1), (2, 2), (2, 3), (3, 1), (3, 2)]
    results = [verify_case(dimension, blocks) for dimension, blocks in cases]
    output = {
        "theorems_checked": ["NRD.7", "NRD.8", "NRD.9"],
        "cases": results,
        "totals": {
            "state_environment_pairs_checked": sum(
                case["state_environment_pairs_checked"] for case in results
            ),
            "unordered_state_pairs_checked": sum(
                case["unordered_state_pairs_checked"] for case in results
            ),
        },
    }

    rendered = json.dumps(output, indent=2, sort_keys=True) + "\n"
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered)
    print(rendered, end="")


if __name__ == "__main__":
    main()
